#!/usr/bin/env python3
"""gen_index.py — generate docs/index.md from the live inventory.

The one-page library card: every skill, its phase, and its trigger,
in printable order. Generated, never hand-edited — CI regenerates and
diffs, so the index cannot drift from the library. Run via `make index`
or directly; write is LF-forced so the diff is byte-stable on every OS.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIRETEST = ROOT / "scripts" / "firetest.py"
TARGET = ROOT / "docs" / "index.md"

PHASE_ORDER = ["gather", "spec", "design", "build", "verify", "ship", "tend", "meta"]
PHASE_GLOSS = {
    "gather": "understand the terrain",
    "spec": "align on what and why",
    "design": "model what outlives the code",
    "build": "make it real, slice by slice",
    "verify": "prove the work",
    "ship": "face reality",
    "tend": "keep it alive",
    "meta": "the library itself",
}


def inventory():
    out = subprocess.run(
        [sys.executable, str(FIRETEST), "--list", "--json"],
        capture_output=True, text=True, check=True,
    ).stdout
    return json.loads(out)


def render(inv):
    lines = [
        "# The Library Index",
        "",
        f"{len(inv)} crafts across the seven fires plus the meta craft. One line",
        "each: the skill, and the door it opens on. Full workflows live in each",
        "skill's `SKILL.md`; the map they hang on is",
        "[lifecycle.md](lifecycle.md).",
        "",
    ]
    for phase in PHASE_ORDER:
        rows = [s for s in inv if s["phase"] == phase]
        if not rows:
            continue
        lines.append(f"## {phase} — {PHASE_GLOSS[phase]} ({len(rows)})")
        lines.append("")
        lines.append("| Skill | Fires when |")
        lines.append("| :- | :- |")
        for s in rows:
            trigger = s["trigger"]
            # strip the leading "Use when" — the table column already says it
            if trigger.lower().startswith("use when"):
                trigger = trigger[8:].lstrip(" ,—-")
            trigger = trigger[0].upper() + trigger[1:] if trigger else trigger
            lines.append(
                f"| [`{s['name']}`](../skills/{s['name']}/SKILL.md) | {trigger} |"
            )
        lines.append("")
    lines += [
        "---",
        "",
        "Generated by `make index` ([`scripts/gen_index.py`](../scripts/gen_index.py))",
        "from the same inventory the Fire Test checks. CI regenerates and diffs",
        "this page on every push — hand edits are overwritten, by design.",
        "",
    ]
    return "\n".join(lines)


def main():
    inv = inventory()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(inv))
    print(f"index written: {TARGET} ({len(inv)} skills)")


if __name__ == "__main__":
    main()
